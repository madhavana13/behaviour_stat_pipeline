"""
Designs beyond 2 x 2: a three-level factor, one-factor and two-factor, validated against
base R / survival (reference_values.json -> k_levels, generated by generate_reference.R).
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from behaviour_stat_pipeline.stats.endpoints.posthoc_cellmeans_prism import run_posthoc_cellmeans_prism
from behaviour_stat_pipeline.stats.endpoints.time_to_event import run_time_to_event
from behaviour_stat_pipeline.stats.endpoints.two_way_anova import run_two_way_anova

HERE = Path(__file__).resolve().parent
REF = json.loads((HERE / "reference_values.json").read_text(encoding="utf-8"))["k_levels"]


@pytest.fixture(scope="module")
def df() -> pd.DataFrame:
    return pd.read_csv(HERE / "fixture.csv")


def close(actual, expected, rtol=1e-8):
    np.testing.assert_allclose(float(actual), float(expected), rtol=rtol, atol=0)


def test_one_way_anova_three_levels(df):
    out = run_two_way_anova(df, assay="REF", endpoint="y", factors=["group3"], typ=2).set_index("term")
    row = out.loc['C(Q("group3"))']
    close(row["F"], REF["oneway"]["F"])
    close(row["p_value"], REF["oneway"]["p"])
    assert row["df"] == REF["oneway"]["df"]
    assert out.loc["Residual", "df"] == REF["oneway"]["df_resid"]


@pytest.mark.parametrize("typ", [2, 3])
def test_two_way_anova_three_by_two(df, typ):
    out = run_two_way_anova(df, assay="REF", endpoint="y", factors=["group3", "sex"], typ=typ).set_index("term")
    ref = REF[f"type{typ}"]
    for term, key in [('C(Q("group3"))', "group3"), ('C(Q("sex"))', "sex"),
                      ('C(Q("group3")):C(Q("sex"))', "interaction")]:
        close(out.loc[term, "F"], ref[key]["F"])
        close(out.loc[term, "p_value"], ref[key]["p"])


def test_posthoc_generated_comparisons_three_levels(df):
    out = run_posthoc_cellmeans_prism(
        df, assay="REF", endpoints=["y"], factors=["group3", "sex"], include_interaction=True,
        factor_orders={"group3": ["a", "b", "c"], "sex": ["female", "male"]},
        comparisons=[{"factor": "group3", "by": ["sex"]}],
    ).set_index("pair_name")
    assert len(out) == len(REF["posthoc"]) == 6
    for name, ref in REF["posthoc"].items():
        row = out.loc[name]
        close(row["diff_a_minus_b"], ref["diff"])
        close(row["se_pooled"], ref["se"])
        close(row["t"], ref["t"])
        close(row["p_value"], ref["p"])
        close(row["p_value_sidak"], ref["p_sidak"])


def test_posthoc_pairs_by_level_name_equal_pairs_by_position(df):
    common = dict(assay="REF", endpoints=["y"], factors=["group", "sex"], include_interaction=True,
                  factor_orders={"group": ["control", "ifs"], "sex": ["female", "male"]})
    by_pos = run_posthoc_cellmeans_prism(df, **common, selected_pairs=[
        {"name": "p", "a": {"group": 0, "sex": 1}, "b": {"group": 1, "sex": 1}}])
    by_name = run_posthoc_cellmeans_prism(df, **common, selected_pairs=[
        {"name": "p", "a": {"group": "control", "sex": "male"}, "b": {"group": "ifs", "sex": "male"}}])
    pd.testing.assert_frame_equal(by_pos, by_name)
    with pytest.raises(ValueError, match="not observed"):
        run_posthoc_cellmeans_prism(df, **common, selected_pairs=[
            {"name": "p", "a": {"group": "stressed", "sex": "male"}, "b": {"group": "ifs", "sex": "male"}}])


def test_time_to_event_three_levels_two_factors(df):
    tests, summary = run_time_to_event(df, assay="REF", endpoint="latency", factors=["group3", "sex"],
                                       trial_duration_s=None, duration_col="rec_s")
    t = tests.set_index("term")
    ref = REF["tte_two_factor"]
    omni = t.loc["group3"]
    assert omni["contrast"] == "omnibus" and omni["lr_df"] == 2
    close(omni["lr_chi2"], ref["group3"]["lr_chi2"], rtol=1e-6)
    close(omni["p_value"], ref["group3"]["p"], rtol=1e-6)
    for lvl in ["b", "c"]:
        row, r = t.loc[f"group3[{lvl} vs a]"], ref[f"hr_{lvl}"]
        close(row["hazard_ratio"], r["hr"], rtol=1e-6)
        close(row["hr_ci_low"], r["ci_low"], rtol=1e-6)
        close(row["hr_ci_high"], r["ci_high"], rtol=1e-6)
        close(row["wald_p"], r["wald_p"], rtol=1e-6)
    close(t.loc["group3:sex", "lr_chi2"], ref["interaction"]["lr_chi2"], rtol=1e-6)
    assert t.loc["group3:sex", "lr_df"] == 2
    lr = tests[tests["model"] == "log-rank"].iloc[0]
    close(lr["lr_chi2"], ref["logrank"]["chi2"], rtol=1e-6)
    close(lr["p_value"], ref["logrank"]["p"], rtol=1e-6)
    assert set(summary["grouping"]) == {"group3", "group3+sex"}


def test_time_to_event_one_factor(df):
    tests, summary = run_time_to_event(df, assay="REF", endpoint="latency", factors=["group3"],
                                       trial_duration_s=None, duration_col="rec_s")
    t = tests.set_index("term")
    ref = REF["tte_one_factor"]
    close(t.loc["group3", "lr_chi2"], ref["lr_chi2"], rtol=1e-6)
    close(t.loc["group3", "p_value"], ref["p"], rtol=1e-6)
    lr = tests[tests["model"] == "log-rank"].iloc[0]
    assert lr["term"] == "group3 (log-rank)"
    close(lr["lr_chi2"], ref["logrank_chi2"], rtol=1e-6)
    close(lr["p_value"], ref["logrank_p"], rtol=1e-6)
    assert set(summary["grouping"]) == {"group3"}
